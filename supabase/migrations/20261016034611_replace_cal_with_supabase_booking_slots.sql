-- Supabase is the source of truth for recurring availability and slot holds.
create table if not exists public.booking_availability_rules (
  id bigint generated by default as identity primary key,
  iso_day_of_week smallint not null check (iso_day_of_week between 1 and 7),
  start_time time not null,
  end_time time not null,
  slot_duration_minutes integer not null default 30
    check (slot_duration_minutes between 15 and 480),
  time_zone text not null default 'Pacific/Auckland'
    check (time_zone = 'Pacific/Auckland'),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (end_time > start_time),
  unique (iso_day_of_week, start_time, end_time, time_zone)
);

alter table public.booking_availability_rules enable row level security;
revoke all on table public.booking_availability_rules from public, anon, authenticated;
revoke all on sequence public.booking_availability_rules_id_seq from public, anon, authenticated;
grant select, insert, update, delete on table public.booking_availability_rules to service_role;
grant usage, select on sequence public.booking_availability_rules_id_seq to service_role;

-- Match the former Cal.com schedule: 30-minute slots, 9am-5pm on
-- Monday, Tuesday, Wednesday and Friday in Auckland time.
insert into public.booking_availability_rules (
  iso_day_of_week,
  start_time,
  end_time,
  slot_duration_minutes
)
select day_number, time '09:00', time '17:00', 30
from unnest(array[1, 2, 3, 5]::smallint[]) as day_number
on conflict (iso_day_of_week, start_time, end_time, time_zone) do nothing;

-- A pending or paid request owns a start time. The partial unique index is the
-- final concurrency guard when two customers submit the same slot together.
create unique index if not exists customer_requests_active_booking_slot_key
  on public.customer_requests (cal_start_at)
  where request_kind = 'booking'
    and payment_status in ('pending', 'paid');

create index if not exists customer_requests_booking_slot_lookup_idx
  on public.customer_requests (cal_start_at, payment_status)
  where request_kind = 'booking';

create or replace function public.get_available_booking_slots(
  p_start timestamptz,
  p_end timestamptz
)
returns table (start_at timestamptz, end_at timestamptz)
language sql
stable
security invoker
set search_path = ''
as $$
  with local_days as (
    select generated_day::date as local_day
    from generate_series(
      (p_start at time zone 'Pacific/Auckland')::date,
      (p_end at time zone 'Pacific/Auckland')::date,
      interval '1 day'
    ) as generated_day
  ),
  local_slots as (
    select
      generate_series(
        day.local_day + rule.start_time,
        day.local_day + rule.end_time
          - make_interval(mins => rule.slot_duration_minutes),
        make_interval(mins => rule.slot_duration_minutes)
      ) as local_start,
      rule.slot_duration_minutes
    from local_days as day
    join public.booking_availability_rules as rule
      on rule.iso_day_of_week = extract(isodow from day.local_day)::smallint
     and rule.active
     and rule.time_zone = 'Pacific/Auckland'
  ),
  zoned_slots as (
    select
      local_start at time zone 'Pacific/Auckland' as start_at,
      (local_start + make_interval(mins => slot_duration_minutes))
        at time zone 'Pacific/Auckland' as end_at
    from local_slots
  )
  select slot.start_at, slot.end_at
  from zoned_slots as slot
  where slot.start_at >= greatest(p_start, now())
    and slot.start_at < p_end
    and not exists (
      select 1
      from public.customer_requests as request
      where request.request_kind = 'booking'
        and request.cal_start_at = slot.start_at
        and (
          request.payment_status = 'paid'
          or (
            request.payment_status = 'pending'
            and exists (
              select 1
              from public.stock_reservations as reservation
              where reservation.customer_request_id = request.id
                and reservation.status = 'pending'
                and reservation.expires_at > now()
            )
          )
        )
    )
  order by slot.start_at;
$$;

revoke all on function public.get_available_booking_slots(timestamptz, timestamptz)
from public, anon, authenticated;
grant execute on function public.get_available_booking_slots(timestamptz, timestamptz)
to service_role;

create or replace function public.search_admin_bookings(
  p_query text default '',
  p_delivery_only boolean default false,
  p_limit integer default 25,
  p_offset integer default 0
)
returns table (
  id uuid,
  request_kind text,
  service_slug text,
  first_name text,
  last_name text,
  email text,
  phone text,
  street_address text,
  address_line_2 text,
  city text,
  postcode text,
  preferred_date date,
  preferred_time text,
  cal_start_at timestamptz,
  cal_time_zone text,
  payment_status text,
  status text,
  message text,
  created_at timestamptz,
  total_count bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  with filtered as (
    select request.*
    from public.customer_requests as request
    where request.request_kind = 'booking'
      and request.payment_status = 'paid'
      and (
        not p_delivery_only
        or (
          request.status = 'confirmed'
          and request.service_slug in ('skip-2-u', 'h2o-2-u')
        )
      )
      and (
        btrim(coalesce(p_query, '')) = ''
        or position(
          lower(btrim(p_query)) in lower(concat_ws(' ',
            request.id::text,
            request.first_name,
            request.last_name,
            request.email,
            request.phone,
            request.street_address,
            request.address_line_2,
            request.city,
            request.postcode,
            request.service_slug
          ))
        ) > 0
      )
  )
  select
    request.id,
    request.request_kind,
    request.service_slug,
    request.first_name,
    request.last_name,
    request.email,
    request.phone,
    request.street_address,
    request.address_line_2,
    request.city,
    request.postcode,
    request.preferred_date,
    request.preferred_time,
    request.cal_start_at,
    request.cal_time_zone,
    request.payment_status,
    request.status,
    request.message,
    request.created_at,
    count(*) over () as total_count
  from filtered as request
  order by
    case when p_delivery_only then request.cal_start_at end asc nulls last,
    request.created_at desc,
    request.id desc
  limit greatest(1, least(coalesce(p_limit, 25), 100))
  offset greatest(coalesce(p_offset, 0), 0);
$$;

revoke all on function public.search_admin_bookings(text, boolean, integer, integer)
from public, anon, authenticated;
grant execute on function public.search_admin_bookings(text, boolean, integer, integer)
to service_role;

create or replace function public.admin_complete_delivery(
  p_request_id uuid,
  p_admin_user_id uuid
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if not exists (
    select 1
    from public.admin_users
    where user_id = p_admin_user_id
      and active = true
  ) then
    raise exception 'ADMIN_ACCESS_DENIED';
  end if;

  update public.customer_requests
  set status = 'completed',
      updated_at = now()
  where id = p_request_id
    and request_kind = 'booking'
    and payment_status = 'paid'
    and status = 'confirmed'
    and service_slug in ('skip-2-u', 'h2o-2-u');

  return found;
end;
$$;

revoke all on function public.admin_complete_delivery(uuid, uuid)
from public, anon, authenticated;
grant execute on function public.admin_complete_delivery(uuid, uuid)
to service_role;

